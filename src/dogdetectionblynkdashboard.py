# ================== CONFIGURATION ==================
# Blynk Settings
BLYNK_AUTH_TOKEN = "uEnVOzsWof-pQaHzKwHv4HSxkOZJRqsp"
V_DOGS_CURRENT = 'V0'     # Current dogs in frame (integer)
V_CONFIDENCE = 'V1'      # Confidence value (float, 0.0 when no dog)
V_DETECTION_STATUS = 'V2' # "Dog Detected" or "No Dog" (string)
V_TIMESTAMP = 'V3'        # Timestamp (string)
V_LOCATION = 'V5'        # Street location (string)

# Location Mapping (customize these coordinates)
LOCATION_MAPPING = {
    (0, 300): "Main Street",    # Left side of frame
    (300, 640): "Park Avenue"   # Right side of frame
}

# Detection Parameters
FRAME_SKIP = 15           # Process every 15th frame
MIN_CONFIDENCE = 0.82     # Minimum confidence to count as detection
MIN_DETECTION_GAP = 1.0   # Seconds between counting the same dog

# ================== HELPER FUNCTIONS ==================
def get_location(x_center):
    """Convert x-coordinate to street name."""
    for (x_min, x_max), location in LOCATION_MAPPING.items():
        if x_min <= x_center < x_max:
            return location
    return "Unknown Area"

def blynk_update(pin, value):
    """Send data to Blynk."""
    try:
        url = f"https://blynk.cloud/external/api/update?token={BLYNK_AUTH_TOKEN}&{pin}={quote(str(value))}"
        return requests.get(url, timeout=3).status_code == 200
    except:
        return False

def blynk_notify(message):
    """Send Blynk notification."""
    try:
        url = f"https://blynk.cloud/external/api/notify?token={BLYNK_AUTH_TOKEN}&message={quote(message)}"
        return requests.get(url).status_code == 200
    except:
        return False

def get_current_timestamp():
    """Get current timestamp in the correct timezone."""
    return datetime.now(timezone).strftime("%Y-%m-%d (%H:%M:%S)")

